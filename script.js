// ============================================================
// 📊 CALCULATE TYPING
// ============================================================

function calculateTyping() {

    let input =
        document.getElementById(
            "typingInput"
        );


    if (!input) {

        return;

    }


    let typedText =
        input.value;


    let originalText =
        document.getElementById(
            "typingText"
        ).innerText;


    if (
        typedText.length === 0
    ) {

        document.getElementById(
            "wpm"
        ).innerText =
            "0";

        return;

    }


    let words =
        typedText
        .trim()
        .split(/\s+/)
        .filter(
            function(word) {

                return word.length > 0;

            }
        );


    let elapsedSeconds =
        totalLevelTime -
        typingTime;


    if (
        elapsedSeconds <= 0
    ) {

        return;

    }


    let minutes =
        elapsedSeconds / 60;


    let wpm =
        Math.round(
            words.length /
            minutes
        );


    document.getElementById(
        "wpm"
    ).innerText =
        wpm;


    let correctCharacters = 0;


    for (
        let i = 0;
        i < typedText.length;
        i++
    ) {

        if (
            typedText[i] ===
            originalText[i]
        ) {

            correctCharacters++;

        }

    }


    let accuracy =
        Math.round(
            (
                correctCharacters /
                typedText.length
            ) * 100
        );


    accuracy =
        Math.min(
            accuracy,
            100
        );


    document.getElementById(
        "accuracy"
    ).innerText =
        accuracy;

}



