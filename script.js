    // Science

    if (selectedSubject === "Science") {

        subjectData =
            subjectQuestions.Science[
                selectedScienceLevel
            ];

    }

    // Other subjects

    else {

        subjectData =
            subjectQuestions[
                selectedSubject
            ];

    }


    if (
        !subjectData ||
        subjectData.length === 0
    ) {

        alert(
            "Questions are not available for this section yet."
        );

        return;

    }


    quizQuestions =
        shuffle(subjectData)
        .slice(
            0,
            Math.min(
                totalQuestions,
                subjectData.length
            )
        );


    currentQuestion = 0;

    score = 0;


