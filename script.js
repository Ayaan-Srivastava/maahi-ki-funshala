let quizQuestions = [];

let currentQuestion = 0;

let score = 0;

let selectedSubject = "";

const totalQuestions = 10;


// ============================================
// SHUFFLE
// ============================================

function shuffle(array) {

    let result = [...array];

    for (
        let i = result.length - 1;
        i > 0;
        i--
    ) {

        let j =
            Math.floor(
                Math.random() * (i + 1)
            );

        [
            result[i],
            result[j]
        ] =
        [
            result[j],
            result[i]
        ];

    }

    return result;
}


// ============================================
// SELECT SUBJECT
// ============================================

function selectSubject(subject, button) {

    selectedSubject = subject;


    let buttons =
        document.querySelectorAll(
            ".subject-btn"
        );


    buttons.forEach(
        function(btn) {

            btn.classList.remove(
                "active"
            );

        }
    );


    button.classList.add("active");

}


// ============================================
// START SELECTED QUIZ
// ============================================

function beginSelectedQuiz() {

    if (selectedSubject === "") {

        alert(
            "Please select a subject first! 📚"
        );

        return;

    }


    let subjectData =
        subjectQuestions[selectedSubject];


    quizQuestions =
        shuffle(subjectData)
        .slice(0, totalQuestions);


    currentQuestion = 0;

    score = 0;


    let subjectSelection =
        document.getElementById(
            "subjectSelection"
        );


    let quizArea =
        document.getElementById(
            "quizArea"
        );


    if (subjectSelection) {

        subjectSelection.style.display =
            "none";

    }


    if (quizArea) {

        quizArea.style.display =
            "block";

    }


    let scoreElement =
        document.getElementById(
            "score"
        );


    if (scoreElement) {

        scoreElement.innerText =
            "Score: 0";

    }


    showQuestion();

}


// ============================================
// OLD START QUIZ
// ============================================
// Kept for compatibility.
// If another quiz page calls startQuiz(),
// it will still work.

function startQuiz() {

    if (
        !document.getElementById(
            "quizArea"
        )
    ) {

        return;

    }


    if (selectedSubject === "") {

        return;

    }


    beginSelectedQuiz();

}


// ============================================
// SHOW QUESTION
// ============================================

function showQuestion() {

    let current =
        quizQuestions[currentQuestion];


    if (!current) {

        return;

    }


    let questionNumber =
        document.getElementById(
            "questionNumber"
        );


    let question =
        document.getElementById(
            "question"
        );


    let options =
        document.getElementById(
            "options"
        );


    if (
        !questionNumber ||
        !question ||
        !options
    ) {

        return;

    }


    questionNumber.innerText =
        "Question " +
        (currentQuestion + 1) +
        " / " +
        totalQuestions;


    question.innerText =
        current.question;


    options.innerHTML = "";


    current.options.forEach(
        function(option) {

            let button =
                document.createElement(
                    "button"
                );


            button.className =
                "option";


            button.innerText =
                option;


            button.onclick =
                function() {

                    checkAnswer(
                        button,
                        option
                    );

                };


            options.appendChild(
                button
            );

        }
    );


    let nextBtn =
        document.getElementById(
            "nextBtn"
        );


    if (nextBtn) {

        nextBtn.style.display =
            "none";

    }


    let submitBtn =
        document.getElementById(
            "submitBtn"
        );


    if (submitBtn) {

        submitBtn.style.display =
            "none";

    }

}


// ============================================
// CHECK ANSWER
// ============================================

function checkAnswer(
    button,
    selectedAnswer
) {

    let current =
        quizQuestions[currentQuestion];


    let allOptions =
        document.querySelectorAll(
            ".option"
        );


    allOptions.forEach(
        function(option) {

            option.disabled = true;

        }
    );


    if (
        selectedAnswer ===
        current.answer
    ) {

        button.classList.add(
            "correct"
        );


        score++;


        let scoreElement =
            document.getElementById(
                "score"
            );


        if (scoreElement) {

            scoreElement.innerText =
                "Score: " + score;

        }

    }

    else {

        button.classList.add(
            "wrong"
        );


        allOptions.forEach(
            function(option) {

                if (
                    option.innerText ===
                    current.answer
                ) {

                    option.classList.add(
                        "correct"
                    );

                }

            }
        );

    }


    // Last question = Submit

    if (
        currentQuestion ===
        totalQuestions - 1
    ) {

        let submitBtn =
            document.getElementById(
                "submitBtn"
            );


        if (submitBtn) {

            submitBtn.style.display =
                "inline-block";

        }

        else {

            // If submit button isn't in HTML,
            // create one automatically.

            let newSubmit =
                document.createElement(
                    "button"
                );


            newSubmit.id =
                "submitBtn";


            newSubmit.className =
                "btn";


            newSubmit.innerText =
                "✅ Submit Quiz";


            newSubmit.onclick =
                submitQuiz;


            document.getElementById(
                "quizArea"
            ).appendChild(
                newSubmit
            );

        }

    }

    else {

        let nextBtn =
            document.getElementById(
                "nextBtn"
            );


        if (nextBtn) {

            nextBtn.style.display =
                "inline-block";

        }

    }

}


// ============================================
// NEXT QUESTION
// ============================================

function nextQuestion() {

    currentQuestion++;


    if (
        currentQuestion <
        totalQuestions
    ) {

        showQuestion();

    }

}


// ============================================
// SUBMIT QUIZ
// ============================================

function submitQuiz() {

    showResult();

}


// ============================================
// QUIZ RESULT
// ============================================

function showResult() {

    let quizBox =
        document.getElementById(
            "quizBox"
        );


    if (!quizBox) {

        return;

    }


    let percentage =
        Math.round(
            (
                score /
                totalQuestions
            ) * 100
        );


    quizBox.innerHTML = `

        <div class="result">

            <h2>
                🎉 Quiz Completed!
            </h2>

            <h2>
                ${selectedSubject}
            </h2>

            <h2>
                ${score} / ${totalQuestions}
            </h2>

            <p>
                Your Score:
                ${percentage}%
            </p>

            <button
                class="btn"
                onclick="location.reload()">

                🔄 Play Again

            </button>

        </div>

    `;

}


