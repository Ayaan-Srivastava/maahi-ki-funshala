// ❓ SHOW QUESTION
// ============================================================

function showQuestion() {

    let current =
        quizQuestions[currentQuestion];


    if (!current) {

        return;

    }


    let questionNumber =
        document.getElementById(
            "questionNumber"
        );


    let question =
        document.getElementById(
            "question"
        );


    let options =
        document.getElementById(
            "options"
        );


    if (
        !questionNumber ||
        !question ||
        !options
    ) {

        return;

    }


    questionNumber.innerText =
        "Question " +
        (currentQuestion + 1) +
        " / " +
        quizQuestions.length;


    question.innerText =
        current.question;


    options.innerHTML = "";


    // Create options

    current.options.forEach(
        function(option) {

            let button =
                document.createElement(
                    "button"
                );


            button.className =
                "option";


            button.innerText =
                option;


            button.onclick =
                function() {

                    checkAnswer(
                        button,
                        option
                    );

                };


            options.appendChild(
                button
            );

        }
    );


    // Hide buttons

    let nextBtn =
        document.getElementById(
            "nextBtn"
        );


    let submitBtn =
        document.getElementById(
            "quizSubmitBtn"
        );


    let backBtn =
        document.getElementById(
            "backSubjectBtn"
        );


    if (nextBtn) {

        nextBtn.style.display =
            "none";

    }


    if (submitBtn) {

        submitBtn.style.display =
            "none";

    }


    if (backBtn) {

        backBtn.style.display =
            "none";

    }

}



// ============================================================
// ✅ CHECK ANSWER
// ============================================================

function checkAnswer(
    button,
    selectedAnswer
) {

    let current =
        quizQuestions[currentQuestion];


    let allOptions =
        document.querySelectorAll(
            ".option"
        );


    // Disable all options

    allOptions.forEach(
        function(option) {

            option.disabled = true;

        }
    );


    // Correct answer

    if (
        selectedAnswer ===
        current.answer
    ) {

        button.classList.add(
            "correct"
        );


        score++;


        let scoreElement =
            document.getElementById(
                "score"
            );


        if (scoreElement) {

            scoreElement.innerText =
                "Score: " + score;

        }

    }


    // Wrong answer

    else {

        button.classList.add(
            "wrong"
        );


        allOptions.forEach(
            function(option) {

                if (
                    option.innerText ===
                    current.answer
                ) {

                    option.classList.add(
                        "correct"
                    );

                }

            }
        );

    }


    // Last question

    if (
        currentQuestion ===
        quizQuestions.length - 1
    ) {

        let submitBtn =
            document.getElementById(
                "quizSubmitBtn"
            );


        if (submitBtn) {

            submitBtn.style.display =
                "inline-block";

        }

    }


    // Other questions

    else {

        let nextBtn =
            document.getElementById(
                "nextBtn"
            );


        if (nextBtn) {

            nextBtn.style.display =
                "inline-block";

        }

    }

}



